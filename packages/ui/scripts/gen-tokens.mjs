#!/usr/bin/env node
// Generates src/tokens/tokens.css from design-system/tokens.json.
// tokens.json is a verbatim copy of the Ryozan Studio Design System
// artifact's project/tokens.json (BTTCO Modern Classic). Do not hand-edit the
// output; re-copy tokens.json from the artifact and re-run `npm run tokens:gen`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const tokens = JSON.parse(readFileSync(join(root, 'design-system/tokens.json'), 'utf8'));
const productionOnly = readFileSync(join(root, 'src/tokens/production-only.css'), 'utf8');

const themes = tokens.color.themes.map((t) => t.id);
const first = themes[0];
const val = (t, theme) => (typeof t.value === 'string' ? t.value : (t.value[theme] ?? t.value[first]));
const cssValue = (v) => (typeof v === 'string' && /^\{[a-z0-9_.-]+\}$/i.test(v) ? `var(--${v.slice(1, -1)})` : v);

const lines = [];
lines.push('/* ══════════════════════════════════════════════════════');
lines.push('   @bttco/ui — token source (BTTCO Modern Classic)');
lines.push('   GENERATED by scripts/gen-tokens.mjs from design-system/tokens.json,');
lines.push('   a verbatim copy of the Ryozan Studio Design System artifact.');
lines.push('   Do not edit by hand. Both vocabularies live here: the website (_ds)');
lines.push('   names and the portal (Relic) names, one value set, two themes.');
lines.push('   ══════════════════════════════════════════════════════ */');
lines.push('');

const family = (key, label) => {
  const fam = tokens[key];
  if (!fam || !fam.tokens) return [];
  const out = [`  /* ── ${label} ── */`];
  for (const t of fam.tokens) out.push(`  --${t.name}: ${cssValue(val(t, first))};`);
  return out;
};

lines.push(`:root, [data-theme="${first}"] {`);
lines.push(...family('color', 'Color'));
lines.push(...family('shadow', 'Shadow'));
lines.push('}');
lines.push('');
for (const theme of themes.slice(1)) {
  lines.push(`[data-theme="${theme}"] {`);
  for (const key of ['color', 'shadow']) {
    for (const t of tokens[key]?.tokens ?? []) {
      if (typeof t.value === 'string') continue;
      if (t.value[theme] === undefined || t.value[theme] === t.value[first]) continue;
      lines.push(`  --${t.name}: ${cssValue(t.value[theme])};`);
    }
  }
  lines.push('}');
  lines.push('');
}

lines.push(':root {');
lines.push(...family('spacing', 'Spacing and website radii'));
lines.push(...family('radius', 'Radius'));
lines.push(...family('fontSize', 'Font size scale'));
lines.push(...family('letterSpacing', 'Letter spacing'));
lines.push(...family('lineHeight', 'Line height'));
lines.push(...family('other', 'Weights, fluid sizes, motion, field, seam'));
lines.push('  /* ── Font families ── */');
for (const [key, stack] of Object.entries(tokens.type.families)) lines.push(`  --font-${key}: ${stack};`);
lines.push('}');
lines.push('');
lines.push('/* ── Type styles (.ds-<name>) ── */');
for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    const fam = s.family ?? group.family;
    const decl = [`font-family: var(--font-${fam})`, `font-size: ${s.fontSize}`];
    if (s.lineHeight !== undefined) decl.push(`line-height: ${s.lineHeight}`);
    if (s.fontWeight !== undefined) decl.push(`font-weight: ${s.fontWeight}`);
    if (s.letterSpacing) decl.push(`letter-spacing: ${s.letterSpacing}`);
    lines.push(`.ds-${s.name} { ${decl.join('; ')}; }`);
  }
}
lines.push('');
lines.push('/* ── Production-only names (src/tokens/production-only.css) ──');
lines.push('   Used by app code but not yet in the design system artifact. */');
lines.push(productionOnly.trim());
lines.push('');

writeFileSync(join(root, 'src/tokens/tokens.css'), lines.join('\n'));
const count = ['color','spacing','radius','shadow','fontSize','other','letterSpacing','lineHeight'].reduce((n,k)=>n+(tokens[k]?.tokens?.length??0),0);
console.log(`tokens.css written: ${count} tokens, ${Object.keys(tokens.type.families).length} families, ${tokens.type.groups.reduce((n,g)=>n+g.styles.length,0)} type styles, ${themes.length} themes`);
